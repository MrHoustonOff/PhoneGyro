for _a, _b in _still:
    assert scene_code.count(_a) == 1, _a
    scene_code = scene_code.replace(_a, _b)
gyro_file = (
    "// GENERATED by tools/design-css/build.py from docs/internal/Design/components/bundle.js\n"
    "// (PhoneGyro: loadGLB, tintGamepad, createScene). Do not edit.\n"
    "const rootScope = typeof window !== 'undefined' ? window : globalThis;\n"
    "const PG = rootScope.PhoneGyro = rootScope.PhoneGyro || {};\n\n"
    + scene_code + "\n\n"
    "export const loadGLB = PG.loadGLB;\n"
    "export const tintGamepad = PG.tintGamepad;\n"
    "export const createScene = PG.createScene;\n"
    "export default PG.createScene;\n"
)
(OUT / "js" / "vendor" / "gyroscene.js").write_text(gyro_file, encoding="utf-8", newline="\n")
print("gyroscene.js", (OUT / "js" / "vendor" / "gyroscene.js").stat().st_size, "bytes")

