     "function setView(v) { if (v === 'front') cam.position.set(0, 2.15, 5.7); else if (v === 'high') cam.position.set(0, 4.6, 6.4); else cam.position.set(2.5, 2.4, 7.1); cam.lookAt(0, -.12, 0); } setView(opts.view); "
