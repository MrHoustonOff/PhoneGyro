from units import px_to_rem  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
DESIGN = ROOT / "docs" / "internal" / "Design"
OUT = ROOT / "gui" / "frontend" / "src"

tokens = (DESIGN / "tokens.css").read_text(encoding="utf-8")
bundle = (DESIGN / "components" / "bundle.css").read_text(encoding="utf-8")

# Fonts live in src/fonts, the stylesheet in src/css.
tokens = tokens.replace('url("fonts/', 'url("../fonts/')

# Texture variables: grain as WebP files, rings from the procedural generator
# (js/rings.js sets --tex-rings-gen-*) with the design tile as the fallback.
grains = re.findall(r'--tex-grain:url\("data:image/png;base64,([^"]+)"\)', bundle)
assert len(grains) == 2, "expected light and dark grain"
try:
    from PIL import Image

    for name, b64 in zip(("light", "dark"), grains):
        img = Image.open(io.BytesIO(base64.b64decode(b64)))
        img.save(OUT / "img" / f"grain-{name}.webp", "WEBP", lossless=True, method=6)
except ImportError:
    print("Pillow missing: grain WebP files not rewritten")

bundle = re.sub(
    r':root,\[data-theme="light"\]\{--tex-rings:url\("data:[^"]+"\);--tex-grain:url\("data:[^"]+"\)\}',
    ':root,[data-theme="light"]{--tex-rings:var(--tex-rings-gen-light,url(../img/rings-light.svg));--tex-grain:url(../img/grain-light.webp)}',
    bundle,
)
bundle = re.sub(
    r'\[data-theme="dark"\]\{--tex-rings:url\("data:[^"]+"\);--tex-grain:url\("data:[^"]+"\)\}',
    '[data-theme="dark"]{--tex-rings:var(--tex-rings-gen-dark,url(../img/rings-dark.svg));--tex-grain:url(../img/grain-dark.webp)}',
    bundle,
)
