package main

// Порог микро-тремора (настройка «Порог микро-тремора рук», по умолчанию 0.10°/с).
//
// Прежняя формула умножала вектор скорости на (|ω| − порог) / |ω|, то есть
// вычитала порог из ЛЮБОГО движения: медленная доводка прицела на 1°/с теряла
// 10% скорости, на 0.3°/с — треть. Как раз самые точные движения гироскопом.
//
// Теперь порог работает только около нуля (как и обещает подсказка в настройках):
//   - |ω| ≤ порог      → 0: дрожь в покое глушится полностью, как раньше;
//   - |ω| ≥ 2·порог    → без изменений: никакой потери скорости;
//   - между ними       → плавный переход по кубическому эрмитову сплайну,
//     гладкий и по значению, и по наклону на обоих концах (без рывков).
// Направление вектора не меняется — масштабируется только модуль.

// deadbandScale возвращает множитель для вектора угловой скорости с модулем speed.
func deadbandScale(speed, threshold float64) float64 {
	if threshold <= 0 {
		return 1
	}
	if speed <= threshold {
		return 0
	}
	if speed >= 2*threshold {
		return 1
	}
	// t ∈ (0,1): выход = порог·p(t), p(t) = 5t² − 3t³:
	// p(0)=0, p'(0)=0 (плавный выход из нуля), p(1)=2, p'(1)=1 (стык с тождеством).
	t := (speed - threshold) / threshold
	out := threshold * t * t * (5 - 3*t)
	return out / speed
}
